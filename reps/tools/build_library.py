#!/usr/bin/env python3
"""Builds the bundled exercise library from yuhonas/free-exercise-db (public domain, Unlicense).

Usage: python3 tools/build_library.py /path/to/free-exercise-db

Writes:
  app/src/data/exercises.json        the library
  app/src/data/images.ts             generated require() map for the pictures
  app/assets/exercises/t/*.webp      square thumbnails
  app/assets/exercises/f/*.webp      two frames per exercise (start / end position)
  backend/library.json               the same library for the server (it loads it on first use), so ids match

To use your own artwork for an exercise, drop replacements into app/assets/exercises with the same
file names (see `n` in exercises.json) and rebuild the app; this script is only needed to regenerate everything.
"""
import io, json, re, shutil, sys
from pathlib import Path
from PIL import Image

src = Path(sys.argv[1])
root = Path(__file__).resolve().parent.parent
data = root / "app" / "src" / "data"
assets = root / "app" / "assets" / "exercises"
for d in (assets / "t", assets / "f"):
    shutil.rmtree(d, ignore_errors=True)
    d.mkdir(parents=True)
data.mkdir(parents=True, exist_ok=True)

EQUIP = {"body only": "bodyweight", "kettlebells": "kettlebell", "bands": "band", "e-z curl bar": "ez bar", None: "other"}
ID_OK = re.compile(r"^[A-Za-z0-9_-]{2,64}$")

def save(img, path, quality):
    img.save(path, "WEBP", quality=quality, method=6)

items, server, thumbs, frames = [], [], [], []
for n, e in enumerate(sorted(json.load(open(src / "dist" / "exercises.json")), key=lambda x: x["name"].lower()), start=1):
    eid = e["id"]
    if not ID_OK.match(eid):
        eid = re.sub(r"[^A-Za-z0-9_-]", "_", eid)[:64]
    item = {
        "id": eid,
        "name": e["name"].strip(),
        "muscle_group": (e["primaryMuscles"] or ["other"])[0],
        "secondary": e.get("secondaryMuscles") or [],
        "equipment": EQUIP.get(e.get("equipment"), e.get("equipment")),
        "instructions": [s.strip() for s in e.get("instructions") or [] if s.strip()],
    }
    imgs = [p for p in (src / "exercises" / q for q in e.get("images") or []) if p.exists()]
    if imgs:
        # File names are plain numbers: Android turns asset paths into resource names and would
        # merge names that differ only in punctuation or case.
        first = Image.open(imgs[0]).convert("RGB")
        w, h = first.size
        s = min(w, h)
        save(first.crop(((w - s) // 2, (h - s) // 2, (w + s) // 2, (h + s) // 2)).resize((112, 112), Image.LANCZOS), assets / "t" / f"t{n:04d}.webp", 62)
        thumbs.append((eid, f"t{n:04d}"))
        names = []
        for k, p in enumerate(imgs[:2]):
            im = Image.open(p).convert("RGB")
            im.thumbnail((420, 420), Image.LANCZOS)
            save(im, assets / "f" / f"f{n:04d}{'ab'[k]}.webp", 52)
            names.append(f"f{n:04d}{'ab'[k]}")
        frames.append((eid, names))
        item["n"] = n
    items.append(item)
    server.append([item["id"], item["name"], item["muscle_group"], item["equipment"]])

(data / "exercises.json").write_text(json.dumps(items, separators=(",", ":")))
lines = ["// Generated by tools/build_library.py. Do not edit by hand.", "/* eslint-disable */", "",
         "export const THUMBS: Record<string, number> = {"]
lines += [f"  {json.dumps(i)}: require('../../assets/exercises/t/{f}.webp')," for i, f in thumbs]
lines += ["};", "", "export const FRAMES: Record<string, number[]> = {"]
lines += [f"  {json.dumps(i)}: [{', '.join(f'require(' + chr(39) + '../../assets/exercises/f/' + f + '.webp' + chr(39) + ')' for f in fs)}]," for i, fs in frames]
lines += ["};", ""]
(data / "images.ts").write_text("\n".join(lines))
(root / "backend" / "library.json").write_text(json.dumps(server, separators=(",", ":")))
size = sum(p.stat().st_size for p in assets.rglob("*.webp"))
print(len(items), "exercises;", len(thumbs), "with pictures; images %.1f MB" % (size / 1e6))
